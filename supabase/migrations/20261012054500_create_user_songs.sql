-- Jalankan sekali di Supabase Dashboard → SQL Editor → New query.
-- Aman dijalankan ulang; tidak menghapus data yang sudah ada.

create table if not exists public.user_songs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  task_id text not null,
  prompt text not null default '',
  status text not null default 'processing',
  tracks jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_songs_tracks_is_array check (jsonb_typeof(tracks) = 'array'),
  constraint user_songs_owner_task_unique unique (user_id, task_id)
);

create index if not exists user_songs_user_created_idx
  on public.user_songs (user_id, created_at desc);

alter table public.user_songs enable row level security;

grant select, insert, update, delete on public.user_songs to authenticated;
grant usage, select on sequence public.user_songs_id_seq to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'user_songs'
      and policyname = 'user_songs_owner_all'
  ) then
    create policy user_songs_owner_all
      on public.user_songs
      for all
      to authenticated
      using (auth.uid() = user_id)
      with check (auth.uid() = user_id);
  end if;
end
$$;
